// Copy the public bait record into backend/config/qday-baits.json and frontend/src/data/qday-baits.json, adding the
// first block to index and the planned (team) transactions the breach alarm must not flag. No secret is read.
import fs from 'node:fs';
import path from 'node:path';
import { pub, C4 } from './common.mjs';
const src = JSON.parse(fs.readFileSync(path.join(C4, 'deployments', 'qday-baits.json'), 'utf8'));
const first = src.txs.find((t) => t.hash?.startsWith('0x'));
const fromBlock = Number((await pub.getTransactionReceipt({ hash: first.hash })).blockNumber) - 10;
const planned = src.txs.filter((t) => t.hash?.startsWith('0x')).map((t) => ({ hash: t.hash.toLowerCase(), step: t.step }));
const cfg = {
  note: 'Public facts about the Q-Day drill baits (TEAM-RUN, Diana testnet). Generated by contracts-v4/script/qday/export-config.mjs. Classical keys are NOT in this file; the API serves them only when QDAY_PUBLISH_KEYS=true.',
  fromBlock, router: '0xb0d8fd2379e06ed5d48371b41baa6dd0a31cf209', drop: '0xbc13b9ee91f31ed56932abdb796693515c351f00',
  baits: src.baits.map((b) => ({ ...b, expectedMinWei: b.id === 'B3' ? '100000000000000000' : '200000000000000000' })),
  teamAccounts: src.teamAccounts, planned,
  before: {
    title: 'Robbed on purpose: a Pocket made with the old browser key derivation',
    pocket: '0x803B3ACEf3e7C7c54580663d1BFa05adA8cB6B17', keyAccount: '0x84095015682060930012267203FA5adD2706c1aF',
    theftTx: '0x445b5443b9793485d1bac034e8c3fb0aa5021bd1efdf41a544272b21257b8893',
    keyAccountTheftCosmosTx: '6099946011B4F4EDAC5EB2DEC736820CA56F077EDCEA7CF7FF4EE3E722143A1C',
    explain: 'Before 20 Nov 2026 the browser used one random root as the secp256k1 key and derived the ML-DSA secret as sha256(root | "|mldsa87"). From the classical key alone we derived the post-quantum key and moved 0.04 QOR out of this team test Pocket (0.05 -> 0.01). Fixed in 43cc149 / 28e1755: both keys are now independent one-way hashes of a master seed.',
  },
  after: { pocket: '0xD6b6Fd3D68aD53E8FD6018099A32c01BaB4aa58b', note: 'Same attack against a Pocket with an independent ML-DSA key: 19 attempts, 0 succeeded (docs/qday/FEASIBILITY.md).', exampleRevertTx: '0xddd488e3ebb527033233fb4123c377aa9337c7876636ab65d0fa58270452ea4b' },
};
const out = JSON.stringify(cfg, null, 2) + '\n';
for (const f of [path.join(C4, '..', 'backend', 'config', 'qday-baits.json'), path.join(C4, '..', 'frontend', 'src', 'data', 'qday-baits.json')]) fs.writeFileSync(f, out);
console.log('fromBlock', fromBlock, 'baits', cfg.baits.length, 'planned', planned.length);
