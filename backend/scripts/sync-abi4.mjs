// Regenerates src/abi4.ts (PocketRouter ABI + every v4 custom error) from the Foundry artifacts in contracts-v4/out.
// Usage: node scripts/sync-abi4.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const out4 = path.resolve(here, '..', '..', 'contracts-v4', 'out');
const load = (name) => JSON.parse(fs.readFileSync(path.join(out4, `${name}.sol`, `${name}.json`), 'utf8')).abi;
const router = load('PocketRouter');
const sig = (e) => `${e.name}(${e.inputs.map((i) => i.type).join(',')})`;
const errors = new Map();
for (const n of ['PocketVault', 'PocketDrop', 'DropPool', 'PocketFactory', 'PocketRouter', 'Payout', 'PqcLib', 'PqGuard']) {
  try { for (const e of load(n).filter((x) => x.type === 'error')) errors.set(sig(e), e); } catch { /* library without abi errors */ }
}
// PqcLib is an internal library, so its errors only appear in the contracts that revert with them (Vault/Drop/Pool).
const body = `// GENERATED by scripts/sync-abi4.mjs from contracts-v4/out. Do not edit by hand.
export const routerAbi = ${JSON.stringify(router, null, 2)} as const;

/** Every custom error any v4 contract can bubble through the router. */
export const v4ErrorsAbi = ${JSON.stringify([...errors.values()], null, 2)} as const;
`;
fs.writeFileSync(path.resolve(here, '..', 'src', 'abi4.ts'), body);
console.log('router fns', router.filter((x) => x.type === 'function').length, 'errors', errors.size);
