// Regenerates backend/src/abi.ts from the Foundry artifact once the contract is compiled.
// Usage: node scripts/sync-abi.mjs [path/to/PocketDrop.json]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const artifact = process.argv[2] ?? path.resolve(here, '..', '..', 'contracts', 'out', 'PocketDrop.sol', 'PocketDrop.json');
if (!fs.existsSync(artifact)) {
  console.error('artifact not found:', artifact, '(run forge build in pocketdrop/contracts first)');
  process.exit(1);
}
const { abi } = JSON.parse(fs.readFileSync(artifact, 'utf8'));
if (!Array.isArray(abi) || !abi.length) { console.error('artifact has no abi'); process.exit(1); }
const out = path.resolve(here, '..', 'src', 'abi.ts');
const header = '// GENERATED by scripts/sync-abi.mjs from contracts/out/PocketDrop.sol/PocketDrop.json. Do not edit by hand.\n';
fs.writeFileSync(out, `${header}export const pocketDropAbi = ${JSON.stringify(abi, null, 2)} as const;\n`);
const n = (t) => abi.filter((x) => x.type === t).length;
console.log(`wrote ${out}: ${n('function')} functions, ${n('event')} events, ${n('error')} errors`);
