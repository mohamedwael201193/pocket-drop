// Builds src/components/icons.tsx from @phosphor-icons/core SVGs, keeping only the weights the app uses
// (the React package ships all six weights per icon). Run: node scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const assets = join(root, 'node_modules/@phosphor-icons/core/assets');
// export name -> [phosphor file name, default weight, extra class, extra weights]
const MAP = {
  ArrowRight: ['arrow-right', 'bold', 'ph-arrow'], ChevronRight: ['caret-right', 'bold', 'ph-arrow'], ChevronDown: ['caret-down', 'bold', ''],
  ExternalLink: ['arrow-square-out', 'bold', 'ph-ext'], Check: ['check', 'bold', 'ph-pop'], CheckCircle2: ['check-circle', 'duotone', 'ph-pop'],
  XCircle: ['x-circle', 'duotone', ''], CircleDashed: ['circle-dashed', 'bold', ''], Loader2: ['circle-notch', 'bold', 'ph-spin'],
  RefreshCw: ['arrows-clockwise', 'bold', ''], Copy: ['copy', 'duotone', 'ph-copy'], Compass: ['compass', 'duotone', ''], Cpu: ['cpu', 'duotone', ''],
  Droplets: ['drop', 'duotone', ''], Eye: ['eye', 'duotone', ''], EyeOff: ['eye-slash', 'duotone', ''], Fingerprint: ['fingerprint', 'duotone', ''],
  FlaskConical: ['flask', 'duotone', ''], Gift: ['gift', 'duotone', ''], Globe: ['globe', 'duotone', ''], Hexagon: ['hexagon', 'duotone', ''],
  Inbox: ['tray', 'duotone', '', ['fill']], KeyRound: ['key', 'duotone', ''], Lock: ['lock-simple', 'duotone', ''], MessageCircle: ['chat-circle', 'duotone', ''],
  Play: ['play', 'duotone', ''], Radio: ['broadcast', 'duotone', ''], Scale: ['scales', 'duotone', ''], Send: ['paper-plane-tilt', 'duotone', '', ['fill']],
  Share2: ['share-network', 'duotone', ''], ShieldCheck: ['shield-check', 'duotone', '', ['fill']], ShieldX: ['shield-slash', 'duotone', ''],
  SkipForward: ['skip-forward', 'duotone', ''], TriangleAlert: ['warning', 'duotone', ''], Users: ['users', 'duotone', ''], Wallet: ['wallet', 'duotone', '', ['fill']],
};
const jsx = (svg) => svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
  .replace(/([a-z]+)-([a-z])([a-z]*)=/g, (_, a, b, c) => `${a}${b.toUpperCase()}${c}=`)
  .replace(/<(path|circle|rect|line|polyline|polygon|ellipse)([^>]*?)\s*\/>/g, '<$1$2 />');
const read = (file, w) => jsx(readFileSync(join(assets, w, `${file}${w === 'regular' ? '' : `-${w}`}.svg`), 'utf8').trim());

let out = `/* Generated by scripts/gen-icons.mjs from @phosphor-icons/core. Do not edit by hand.
 * One icon set for the whole app: Phosphor (duotone, bold for arrows and checks), named like the Lucide icons
 * they replaced so call sites stay the same. Hover and state motion live in index.css (.ph-i, .ph-arrow, .ph-pop). */
import { forwardRef, type CSSProperties, type ReactNode } from 'react';

export type IconWeight = 'duotone' | 'bold' | 'fill';
export type IconProps = { className?: string; style?: CSSProperties; 'aria-hidden'?: boolean | 'true' | 'false'; 'aria-label'?: string; weight?: IconWeight; strokeWidth?: number };

function mk(name: string, paths: Partial<Record<IconWeight, ReactNode>>, def: IconWeight, extra: string) {
  const C = forwardRef<SVGSVGElement, IconProps>(function Icon({ className, weight, strokeWidth: _s, ...rest }, ref) {
    void _s;
    const body = paths[weight ?? def] ?? paths[def];
    return (
      <svg ref={ref} xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" width="1em" height="1em" fill="currentColor"
        className={['ph-i', extra, className].filter(Boolean).join(' ')} aria-hidden={rest['aria-label'] ? undefined : true} role={rest['aria-label'] ? 'img' : undefined} {...rest}>
        {body}
      </svg>
    );
  });
  C.displayName = name;
  return C;
}

`;
for (const [name, [file, def, extra, more = []]] of Object.entries(MAP)) {
  const ws = [def, ...more];
  const body = ws.map((w) => `${w}: <>${read(file, w)}</>`).join(', ');
  out += `export const ${name} = mk('${name}', { ${body} }, '${def}', '${extra}');\n`;
}
writeFileSync(join(root, 'src/components/icons.tsx'), out);
console.log('icons.tsx written:', Object.keys(MAP).length, 'icons');
