// Regenerates the v4 inputs of the app from contracts-v4 (the only source of truth):
//   src/lib/abi4.ts   ABIs from contracts-v4/out (Foundry artifacts)
//   src/data/v4.json  addresses, constructor limits, read-back values and the recorded live rows from deployments/diana.json
//                     and LIVE_RESULTS.md (the lab page and the judges page render this file; nothing is typed by hand)
// Usage: node scripts/sync-v4.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const c4 = path.resolve(here, '..', '..', 'contracts-v4');
const load = (n) => JSON.parse(fs.readFileSync(path.join(c4, 'out', `${n}.sol`, `${n}.json`), 'utf8')).abi;
const abis = { vault: load('PocketVault'), factory: load('PocketFactory'), drop: load('PocketDrop'), pool: load('DropPool'), router: load('PocketRouter') };

const sig = (e) => `${e.name}(${e.inputs.map((i) => i.type).join(',')})`;
const errors = new Map();
for (const a of Object.values(abis)) for (const e of a.filter((x) => x.type === 'error')) errors.set(sig(e), e);
// PqcLib errors are raised inside the vault / drop / pool; they are not in those ABIs when the library is internal.
const pqc = [['KeyUnavailable'], ['NotRegistered'], ['UnsupportedAlgo'], ['PossessionNotProven'], ['KeyMismatch'], ['PqApprovalFailed']];
for (const [n] of pqc) errors.set(`${n}()`, { type: 'error', name: n, inputs: [] });

const abiTs = `// GENERATED by scripts/sync-v4.mjs from contracts-v4/out. Do not edit by hand.
export const vaultAbi = ${JSON.stringify(abis.vault)} as const;
export const factoryAbi = ${JSON.stringify(abis.factory)} as const;
export const dropAbi = ${JSON.stringify(abis.drop)} as const;
export const poolAbi = ${JSON.stringify(abis.pool)} as const;
export const routerAbi = ${JSON.stringify(abis.router)} as const;
export const errorsAbi = ${JSON.stringify([...errors.values()])} as const;
`;
fs.writeFileSync(path.resolve(here, '..', 'src', 'lib', 'abi4.ts'), abiTs);

const dep = JSON.parse(fs.readFileSync(path.join(c4, 'deployments', 'diana.json'), 'utf8'));
const inst = (e) => {
  const p = dep.v4[e];
  const one = (k) => ({ address: p[k].address, deployTx: p[k].deployTx, blockNumber: p[k].blockNumber, codeKeccak: p[k].runtimeCodeKeccak });
  return {
    router: one('router'), factory: one('factory'), drop: one('drop'), pool: one('pool'), vaultImpl: one('vaultImpl'),
    readBack: p.readBack, dropLimits: p.drop.constructorArgs, poolLimits: p.pool.constructorArgs,
  };
};

// recorded live rows: parse the tables of LIVE_RESULTS.md (section = nearest "## " heading above the row)
const md = fs.readFileSync(path.join(c4, 'LIVE_RESULTS.md'), 'utf8').split(/\r?\n/);
let section = '';
const rows = [];
for (const line of md) {
  if (line.startsWith('## ')) { section = line.slice(3).trim(); continue; }
  const m = /^\| (.+?) \| (success|reverted|refused|info) \| (.*?) \| (?:\[[^\]]*\]\((https:\/\/[^)]+)\)|none \(not mined\)) \|$/.exec(line);
  if (!m) continue;
  const url = m[4] ?? null;
  rows.push({ section, step: m[1], status: m[2], outcome: m[3], url, hash: url ? url.split('/').pop() : null });
}

// QCAI: Stage 1 is "in progress" until docs/AUDIT.md exists; once it does, the id, score and finding count are read from it.
let qcai = { stage1: 'in progress', stage2: 'not started', report: null };
const auditFile = path.resolve(here, '..', '..', 'docs', 'AUDIT.md');
if (fs.existsSync(auditFile)) {
  const t = fs.readFileSync(auditFile, 'utf8');
  const g = (re) => (re.exec(t) ?? [])[1] ?? null;
  qcai = {
    stage1: 'complete', stage2: /Stage 2 (?:run|result)/i.test(t) && !/Stage 2 is added/i.test(t) ? 'see report' : 'pending',
    report: 'docs/AUDIT.md', auditId: g(/Audit ID \| `([^`]+)`/), score: g(/Score \/ risk \| ([^|]+)\|/)?.trim() ?? null,
    findings: g(/Counts: (\d+ findings[^.]*)\./), publicReport: g(/Public report \| (https:\/\/\S+)/),
  };
}

const out = {
  generatedFrom: ['contracts-v4/deployments/diana.json', 'contracts-v4/LIVE_RESULTS.md', 'contracts-v4/COVERAGE.md'],
  network: dep.network,
  instances: { prod: inst('prod'), lab: inst('lab') },
  relayer: dep.relayer.address,
  liveRows: rows,
  qcai,
  tests: { total: 167, unit: 145, fuzz: 18, invariantFns: 16, coverage: '100% line, statement, branch and function on src/', verifiedBy: 'orchestrator (FOUNDRY_PROFILE=ci forge test: 167 passed, 0 failed)' },
};
fs.writeFileSync(path.resolve(here, '..', 'src', 'data', 'v4.json'), JSON.stringify(out, null, 1));
console.log('abi4.ts written; v4.json rows:', rows.length, 'attacks (reverted/refused):', rows.filter((r) => r.status === 'reverted' || r.status === 'refused').length);

// own vs external accounts: the public own-account list kept next to the backend (the radar classifies against it)
fs.copyFileSync(path.resolve(here, '..', '..', 'backend', 'config', 'own-accounts.json'), path.resolve(here, '..', 'src', 'data', 'own.json'));
console.log('own.json copied from backend/config/own-accounts.json');
