// node scripts/sync-latency.mjs -> builds src/data/latency.json from evidence/v2/e2e-*.json (per-step ms of the recipient flow).
import fs from 'node:fs';
const dir = new URL('../evidence/v2/', import.meta.url);
const runs = fs.readdirSync(dir).filter((f) => /^e2e-.*\.json$/.test(f)).map((f) => JSON.parse(fs.readFileSync(new URL(f, dir), 'utf8')))
  .filter((j) => j.result === 'PASS' && j.stepMs)
  .map((j) => ({ label: `${j.browser} ${j.viewport} ${j.mode}`, date: String(j.startedAt).slice(0, 10), stepsMs: j.stepMs }));
fs.writeFileSync(new URL('../src/data/latency.json', import.meta.url), JSON.stringify({ note: 'Per-step durations of the recipient flow measured by Playwright against the deployed app. Generated by scripts/sync-latency.mjs from evidence/v2/e2e-*.json.', runs }, null, 1));
console.log('runs', runs.length);
