// Generates test/fixtures/pqc.json: REAL ML-DSA-87 keys and signatures (via @qorechain/pqc, the same library the
// QoreChain SDK uses). The Foundry mock verifier accepts exactly the (pk, sig, msg) triples listed here.
//   node script/gen-fixtures.mjs
import fs from 'node:fs';
import { mldsa } from '@qorechain/pqc';
import { keccak256 } from 'viem';
import {
  CHAIN_ID, PD_ADDR, OTHER_ADDR, NUM_LINK_KEYS, NUM_RECIPIENTS, NUM_LINKS, RECIP_ADDRS,
  bindMsg, claimMsg, tripleHash, hex, unhex, linkKeyIndex,
} from './fixtures-lib.mjs';

const linkKeys = Array.from({ length: NUM_LINK_KEYS }, () => mldsa.keygen());
const recipKeys = Array.from({ length: NUM_RECIPIENTS }, () => mldsa.keygen());
const recipHash = recipKeys.map((k) => keccak256(hex(k.publicKey)));
const accepted = new Set();
let signatures = 0;

function sign(key, msgHex) {
  const sig = mldsa.sign(key.secretKey, unhex(msgHex));
  if (!mldsa.verify(key.publicKey, unhex(msgHex), sig)) throw new Error('self-verify failed');
  const sigHex = hex(sig);
  accepted.add(tripleHash(hex(key.publicKey), sigHex, msgHex));
  signatures++;
  return sigHex;
}

const bindSigs = [];
const claimSigs = [];
for (let linkId = 1; linkId <= NUM_LINKS; linkId++) {
  bindSigs.push([]);
  claimSigs.push([]);
  for (let r = 0; r < NUM_RECIPIENTS; r++) {
    const bm = bindMsg({ linkId, recipient: RECIP_ADDRS[r], recipientKeyHash: recipHash[r] });
    bindSigs[linkId - 1].push(sign(linkKeys[linkKeyIndex(linkId)], bm));
    const cm = claimMsg({ linkId, recipient: RECIP_ADDRS[r] });
    claimSigs[linkId - 1].push(sign(recipKeys[r], cm));
  }
}

// Real signatures over the WRONG message (wrong domain, chain id, contract): genuine ML-DSA-87 signatures that must
// NOT verify against the digests the contract computes. The mock accepts them only for their own (wrong) message,
// exactly as the real precompile would.
const L = linkKeys[linkKeyIndex(1)];
const R0 = recipKeys[0];
const wrong = {
  bindDomain: sign(L, bindMsg({ domain: 'POCKETDROP_BIND_V2', linkId: 1, recipient: RECIP_ADDRS[0], recipientKeyHash: recipHash[0] })),
  bindChain: sign(L, bindMsg({ chainId: 1n, linkId: 1, recipient: RECIP_ADDRS[0], recipientKeyHash: recipHash[0] })),
  bindContract: sign(L, bindMsg({ contract: OTHER_ADDR, linkId: 1, recipient: RECIP_ADDRS[0], recipientKeyHash: recipHash[0] })),
  claimDomain: sign(R0, claimMsg({ domain: 'POCKETDROP_BIND_V1', linkId: 1, recipient: RECIP_ADDRS[0] })),
  claimChain: sign(R0, claimMsg({ chainId: 1n, linkId: 1, recipient: RECIP_ADDRS[0] })),
  claimContract: sign(R0, claimMsg({ contract: OTHER_ADDR, linkId: 1, recipient: RECIP_ADDRS[0] })),
};

const out = {
  note: 'Generated by script/gen-fixtures.mjs from real ML-DSA-87 keys (@qorechain/pqc). TEST FIXTURES ONLY: these keys are public and worthless.',
  chainId: Number(CHAIN_ID),
  contract: PD_ADDR,
  linkKeyForLinkId: 'linkPks[linkId % 3]',
  linkPks: linkKeys.map((k) => hex(k.publicKey)),
  recipPks: recipKeys.map((k) => hex(k.publicKey)),
  recipAddrs: RECIP_ADDRS,
  bindSigs, // [linkId-1][recipientIndex]
  claimSigs, // [linkId-1][recipientIndex]
  wrong,
  accepted: [...accepted],
};
fs.writeFileSync(new URL('../test/fixtures/pqc.json', import.meta.url), JSON.stringify(out));
console.log('fixtures written:', accepted.size, 'accepted triples,', signatures, 'signatures');
